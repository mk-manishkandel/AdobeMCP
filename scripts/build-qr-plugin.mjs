/**
 * Builds the Illustrator QR plugins from shared sources, so the MCP tool, the script and the panel use one encoder:
 *   plugins/illustrator/QR Code.jsx             standalone File > Scripts dialog
 *   plugins/illustrator/qr-panel/js/qr-core.js  panel browser code (encoder + payload rules, for the live preview)
 *   plugins/illustrator/qr-panel/jsx/host.jsx   panel Illustrator code (encoder + drawing + placement)
 *
 *   node scripts/build-qr-plugin.mjs           write the files
 *   node scripts/build-qr-plugin.mjs --check   exit 1 if any file is out of date
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const PLUGIN_DIR = join(ROOT, 'plugins', 'illustrator');
export const QR_PANEL_DIR = join(PLUGIN_DIR, 'qr-panel');
export const QR_PLUGIN_PATH = join(PLUGIN_DIR, 'QR Code.jsx');

const SRC = Object.freeze({
  encoder: join(ROOT, 'jsx', 'qr-encoder.jsx'),
  draw: join(ROOT, 'jsx', 'qr-draw.jsx'),
  payloads: join(PLUGIN_DIR, 'src', 'qr-payloads.jsx'),
  place: join(PLUGIN_DIR, 'src', 'qr-place.jsx'),
  dialog: join(PLUGIN_DIR, 'src', 'qr-dialog.jsx'),
  panelHost: join(PLUGIN_DIR, 'src', 'qr-panel-host.jsx'),
});

const GENERATED = 'GENERATED by scripts/build-qr-plugin.mjs - edit jsx/qr-*.jsx or plugins/illustrator/src/ instead.';
const LICENSE = 'MIT License, part of AdobeMCP (https://github.com/mk-manishkandel/AdobeMCP).';

const SCRIPT_HEADER = `#target illustrator
/*
 * QR Code for Adobe Illustrator: creates a native vector QR code (merged compound path).
 * Install: copy this file into "/Applications/Adobe Illustrator <version>/Presets.localized/<locale>/Scripts/"
 * and restart Illustrator; it appears under File > Scripts > QR Code.
 * Or run it once via File > Scripts > Other Script... (Cmd+F12).
 *
 * ${GENERATED}
 * ${LICENSE}
 */
`;

const concat = (files) => files.map((file) => readFileSync(file, 'utf8').trimEnd()).join('\n\n');

/** The standalone script; everything is wrapped in a function so no globals leak into Illustrator. */
export function buildQrPlugin() {
  const body = concat([SRC.encoder, SRC.draw, SRC.payloads, SRC.place, SRC.dialog]);
  return `${SCRIPT_HEADER}\n(function () {\n${body}\n\nqrpMain();\n})();\n`;
}

/** Panel files keyed by absolute path. host.jsx exposes only $.global.QRCodePanel. */
export function buildQrPanelFiles() {
  const core = `/* QR Code panel core: encoder + payload rules for the live preview.\n * ${GENERATED}\n * ${LICENSE} */\n\n` +
    `${concat([SRC.encoder, SRC.payloads])}\n`;
  const host = `/* QR Code panel host script (Illustrator side).\n * ${GENERATED}\n * ${LICENSE} */\n\n` +
    `(function () {\n${concat([SRC.encoder, SRC.draw, SRC.place, SRC.panelHost])}\n})();\n`;
  return {
    [join(QR_PANEL_DIR, 'js', 'qr-core.js')]: core,
    [join(QR_PANEL_DIR, 'jsx', 'host.jsx')]: host,
  };
}

export function buildAll() {
  return { [QR_PLUGIN_PATH]: buildQrPlugin(), ...buildQrPanelFiles() };
}

function readCurrent(path) {
  try {
    return readFileSync(path, 'utf8');
  } catch (err) {
    if (err.code === 'ENOENT') return '';
    throw err;
  }
}

function main(argv) {
  const files = buildAll();
  if (argv.includes('--check')) {
    const stale = Object.keys(files).filter((path) => readCurrent(path) !== files[path]);
    if (stale.length) {
      console.error(`Out of date: ${stale.map((p) => relative(ROOT, p)).join(', ')}. Run: npm run build:qr-plugin`);
      process.exit(1);
    }
    console.log('QR script and panel are up to date.');
    return;
  }
  for (const [path, content] of Object.entries(files)) {
    writeFileSync(path, content);
    console.log(`Wrote ${relative(ROOT, path)}`);
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main(process.argv.slice(2));
