/**
 * Builds the standalone Illustrator script plugins/illustrator/QR Code.jsx from
 *   jsx/qr-encoder.jsx + jsx/qr-draw.jsx + plugins/illustrator/src/qr-dialog.jsx
 * so the dialog and the ai_qr_code MCP tool share one encoder.
 *
 *   node scripts/build-qr-plugin.mjs           write the file
 *   node scripts/build-qr-plugin.mjs --check   exit 1 if the file is out of date
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const QR_PLUGIN_PATH = join(ROOT, 'plugins', 'illustrator', 'QR Code.jsx');
export const QR_PLUGIN_SOURCES = Object.freeze([
  join(ROOT, 'jsx', 'qr-encoder.jsx'),
  join(ROOT, 'jsx', 'qr-draw.jsx'),
  join(ROOT, 'plugins', 'illustrator', 'src', 'qr-dialog.jsx'),
]);

const HEADER = `#target illustrator
/*
 * QR Code for Adobe Illustrator: creates a native vector QR code (merged compound path).
 * Install: copy this file into "/Applications/Adobe Illustrator <version>/Presets.localized/<locale>/Scripts/"
 * and restart Illustrator; it appears under File > Scripts > QR Code.
 * Or run it once via File > Scripts > Other Script... (Cmd+F12).
 *
 * GENERATED by scripts/build-qr-plugin.mjs - edit jsx/qr-*.jsx or plugins/illustrator/src/ instead.
 * MIT License, part of AdobeMCP (https://github.com/mk-manishkandel/AdobeMCP).
 */
`;

/** The full plugin source; everything is wrapped in a function so no globals leak into Illustrator. */
export function buildQrPlugin() {
  const body = QR_PLUGIN_SOURCES.map((file) => readFileSync(file, 'utf8').trimEnd()).join('\n\n');
  return `${HEADER}\n(function () {\n${body}\n\nqrpMain();\n})();\n`;
}

function readCurrent() {
  try {
    return readFileSync(QR_PLUGIN_PATH, 'utf8');
  } catch (err) {
    if (err.code === 'ENOENT') return '';
    throw err;
  }
}

function main(argv) {
  const built = buildQrPlugin();
  if (argv.includes('--check')) {
    if (readCurrent() !== built) {
      console.error(`${QR_PLUGIN_PATH} is out of date. Run: npm run build:qr-plugin`);
      process.exit(1);
    }
    console.log('QR plugin is up to date.');
    return;
  }
  writeFileSync(QR_PLUGIN_PATH, built);
  console.log(`Wrote ${QR_PLUGIN_PATH}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main(process.argv.slice(2));
